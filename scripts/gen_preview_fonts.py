"""Generate the fonts the panel draws layout text with (frontend/fonts.js).

The fonts are Trip5's Matrix-Fonts (MIT), which AWTRIX NG uses for layout
text. Only the characters the preview needs are kept: printable ASCII,
Latin-1 and a few symbols. Run it with the folder of the BDF files, for
example `assets/fonts/matrix-fonts` in a clone of AWTRIX NG or the
`fonts` folder of https://github.com/trip5/Matrix-Fonts:

    python scripts/gen_preview_fonts.py path/to/matrix-fonts
"""

from __future__ import annotations

import json
from pathlib import Path
import sys

FONTS = {
    "matrix-light6": "6-series/MatrixLight6.bdf",
    "matrix-chunky6": "6-series/MatrixChunky6.bdf",
    "matrix-light8": "8-series/MatrixLight8.bdf",
    "matrix-chunky8": "8-series/MatrixChunky8.bdf",
    "matrix-light8x6": "8-series/MatrixLight8x6.bdf",
    "matrix-chunky8x6": "8-series/MatrixChunky8x6.bdf",
}
CHARS = [
    *range(0x20, 0x7F),
    *range(0xA0, 0x100),
    0x2013,  # en dash
    0x2014,  # em dash
    0x2026,  # ellipsis
    0x20AC,  # euro
    0x2103,  # degree Celsius
    0x2109,  # degree Fahrenheit
]
OUT = Path(__file__).parent.parent / "custom_components/awtrix_studio/frontend/fonts.js"

