async def test_screen_mirror(
    hass: HomeAssistant,
    hass_ws_client: WebSocketGenerator,
    entry: MockConfigEntry,
    mqtt_mock: MqttMockHAClient,
    freezer: FrozenDateTimeFactory,
) -> None:
    """The screen is requested while someone watches, and forwarded."""
    client = await hass_ws_client(hass)
    await client.send_json_auto_id(
        {"type": "awtrix_studio/screen", "entry_id": entry.entry_id}
    )
    response = await client.receive_json()
    assert response["success"]
    subscription = response["id"]
    await hass.async_block_till_done()
    assert published(mqtt_mock, f"{PREFIX}/sendscreen") == [""]

    async_fire_mqtt_message(hass, f"{PREFIX}/screen", json.dumps([0xFF0000] * 256))
    await hass.async_block_till_done()
    event = (await client.receive_json())["event"]
    assert event["pixels"][:2] == [0xFF0000, 0xFF0000]

    # Malformed screens are ignored.
    async_fire_mqtt_message(hass, f"{PREFIX}/screen", '["<script>"]')
    await tick(hass, freezer, 1.1)
    assert len(published(mqtt_mock, f"{PREFIX}/sendscreen")) == 2

    # Nobody watching: no more requests.
    await client.send_json_auto_id(
        {"type": "unsubscribe_events", "subscription": subscription}
    )
    await client.receive_json()
    count = len(published(mqtt_mock, f"{PREFIX}/sendscreen"))
    await tick(hass, freezer, 5)
    assert len(published(mqtt_mock, f"{PREFIX}/sendscreen")) == count


