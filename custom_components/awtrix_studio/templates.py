"""Build templates for simple mode.

Simple mode is a form (entity, icon, color, thresholds…) turned into an ordinary
template, so that it runs through exactly the same engine as hand-written
templates. The generated template is readable on purpose: converting an app to
template mode shows it, and it makes a good starting point.

Kept free of Home Assistant imports so it can be tested in isolation.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
import json
import math
import re
from typing import Any

from .const import (
    APP_COLOR_MODES,
    COLOR_FIXED,
    COLOR_GRADIENT,
    COLOR_STATE,
    COLOR_STEPS,
    CONF_ACTIVE_STATE,
    CONF_COLOR,
    CONF_COLOR_1,
    CONF_COLOR_2,
    CONF_COLOR_MODE,
    CONF_DECIMALS,
    CONF_EFFECT,
    CONF_EFFECT_INTERVAL,
    CONF_ENTITY_ID,
    CONF_HIDE_WHEN_ZERO,
    CONF_ICON,
    CONF_LABEL,
    CONF_PROGRESS,
    CONF_PROGRESS_BG,
    CONF_PROGRESS_COLOR,
    CONF_PROGRESS_ENTITY,
    CONF_PROGRESS_MAX,
    CONF_PROGRESS_MIN,
    CONF_SHOW_UNIT,
    CONF_THRESHOLD_1,
    CONF_THRESHOLD_2,
    DEFAULT_ACTIVE_STATE,
    DEFAULT_COLOR,
    DEFAULT_EFFECT_INTERVAL,
    DEFAULT_INDICATOR_COLOR,
    DEFAULT_PROGRESS_BG,
    DEFAULT_PROGRESS_MAX,
    DEFAULT_PROGRESS_MIN,
    EFFECT_NONE,
    EFFECTS,
    FIRMWARE_AWTRIX3,
    FIRMWARE_AWTRIX_NG,
    INDICATOR_COLOR_MODES,
)
from .gradients import InvalidGradientError, jinja_lines, resolve_stops

HEADER = "{#- Generated by Awtrix Studio (simple mode). -#}"

# Everything the user types ends up inside a generated template, so it is
# validated or quoted before being written there; nothing is pasted raw.
ENTITY_ID_RE = re.compile(r"^[a-z0-9_]+\.[a-z0-9_]+$")
HEX_COLOR_RE = re.compile(r"^#[0-9A-Fa-f]{6}$")
MAX_DECIMALS = 4

# What each firmware calls the keys the generated templates write. A simple
# item describes what to show; its template is written in the clock's JSON.
KEYS: dict[str, dict[str, str]] = {
    FIRMWARE_AWTRIX3: {
        "color": "color",
        "progress_color": "progressC",
        "progress_bg": "progressBC",
        "blink": "blink",
        "fade": "fade",
    },
    FIRMWARE_AWTRIX_NG: {
        "color": "textColor",
        "progress_color": "progressColor",
        "progress_bg": "progressTrackColor",
        "blink": "blinkMs",
        "fade": "fadeMs",
    },
}


def _keys(firmware: str) -> dict[str, str]:
    return KEYS.get(firmware, KEYS[FIRMWARE_AWTRIX3])


class InvalidSimpleOptionsError(ValueError):
    """Simple-mode options that cannot be turned into a safe template."""


def _entity_id(value: Any) -> str:
    if not isinstance(value, str) or not ENTITY_ID_RE.fullmatch(value):
        raise InvalidSimpleOptionsError(f"invalid entity id: {value!r}")
    return value


def rgb_to_hex(color: Any, default: Sequence[int]) -> str:
    """Return `#RRGGBB` for an RGB list or a hex string, else the default."""
    if isinstance(color, str):
        return (
            color.upper()
            if HEX_COLOR_RE.fullmatch(color)
            else rgb_to_hex(None, default)
        )
    try:
        channels = [int(c) for c in color] if color else []
    except (TypeError, ValueError):
        channels = []
    if len(channels) != 3:
        channels = [int(c) for c in default]
    red, green, blue = (max(0, min(255, c)) for c in channels)
    return f"#{red:02X}{green:02X}{blue:02X}"


def jinja_str(value: str) -> str:
    """Quote a value as a Jinja string literal.

    JSON string escaping is also valid Jinja string escaping: quotes,
    backslashes and control characters are escaped, so user text can never
    end the literal and be read as template code.
    """
    return json.dumps(str(value), ensure_ascii=False)


def _number(value: Any) -> float | None:
    if value is None or value == "":
        return None
    if isinstance(value, bool):
        return None
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if math.isfinite(number) else None


def app_color_mode(options: Mapping[str, Any]) -> str:
    """How a simple app picks its color (older items have no explicit mode)."""
    mode = options.get(CONF_COLOR_MODE)
    if mode in APP_COLOR_MODES:
        return mode
    if any(
        _number(options.get(key)) is not None
        for key in (CONF_THRESHOLD_1, CONF_THRESHOLD_2)
    ):
        return COLOR_STEPS
    return COLOR_FIXED


def indicator_color_mode(options: Mapping[str, Any]) -> str:
    """How a simple indicator picks its color."""
    mode = options.get(CONF_COLOR_MODE)
    return mode if mode in INDICATOR_COLOR_MODES else COLOR_STATE


def _gradient_lines(options: Mapping[str, Any]) -> list[str]:
    try:
        return jinja_lines(resolve_stops(options))
    except InvalidGradientError as err:
        raise InvalidSimpleOptionsError(str(err)) from err


def build_app_template(
    options: Mapping[str, Any], firmware: str = FIRMWARE_AWTRIX3
) -> str:
    """Template for a simple app: one entity shown as text with an icon."""
    keys = _keys(firmware)
    entity = _entity_id(options.get(CONF_ENTITY_ID))
    label = str(options.get(CONF_LABEL) or "").strip()
    icon = str(options.get(CONF_ICON) or "").strip()
    color = rgb_to_hex(options.get(CONF_COLOR), DEFAULT_COLOR)
    decimals = options.get(CONF_DECIMALS)
    show_unit = options.get(CONF_SHOW_UNIT, True)
    hide_zero = options.get(CONF_HIDE_WHEN_ZERO, False)

    lines = [
        HEADER,
        f"{{%- set raw = states({jinja_str(entity)}) -%}}",
        "{%- set num = raw | float if raw | is_number else none -%}",
        "{%- if raw in ['unknown', 'unavailable', ''] -%}",
        "[]",
    ]
    if hide_zero:
        lines += ["{%- elif num is not none and num == 0 -%}", "[]"]
    lines.append("{%- else -%}")

    if decimals is not None and decimals != "":
        decimals = max(0, min(MAX_DECIMALS, int(decimals)))
    if decimals is None or decimals == "":
        lines.append("{%- set value = raw -%}")
    elif decimals == 0:
        lines.append(
            "{%- set value = num | round(0) | int if num is not none else raw -%}"
        )
    else:
        rounded = f"num | round({int(decimals)})"
        lines.append(f"{{%- set value = {rounded} if num is not none else raw -%}}")

    text = "value | string"
    if label:
        text = f"{jinja_str(label + ' ')} ~ value"
    if show_unit:
        lines += [
            "{%- set unit = state_attr("
            f"{jinja_str(entity)}, 'unit_of_measurement') or '' -%}}",
            # Like Home Assistant: no space before °C, °F or %.
            "{%- set sep = '' if unit[:1] in ['', '°', '%'] else ' ' -%}",
        ]
        text += " ~ sep ~ unit"
    lines.append(f"{{%- set text = {text} -%}}")

    lines.append(f"{{%- set color = {jinja_str(color)} -%}}")
    lines += _color_lines(options)

    payload = f'{{"text": text, "{keys["color"]}": color'
    if icon:
        payload += f', "icon": {jinja_str(icon)}'
    payload += "}"
    if not options.get(CONF_PROGRESS):
        lines += [f"{{{{ {payload} | tojson }}}}", "{%- endif -%}"]
        return "\n".join(lines)

    lines.append(f"{{%- set page = {payload} -%}}")
    lines += _progress_lines(options, entity, keys)
    lines += ["{{ page | tojson }}", "{%- endif -%}"]
    return "\n".join(lines)


def _color_lines(options: Mapping[str, Any]) -> list[str]:
    """Lines changing `color` by steps or along a gradient."""
    lines: list[str] = []
    color_mode = app_color_mode(options)
    if color_mode == COLOR_GRADIENT:
        lines += [
            "{%- if num is not none -%}",
            *_gradient_lines(options),
            "{%- endif -%}",
        ]
    for threshold_key, color_key in (
        (CONF_THRESHOLD_1, CONF_COLOR_1),
        (CONF_THRESHOLD_2, CONF_COLOR_2),
    ):
        if color_mode != COLOR_STEPS:
            break
        threshold = _number(options.get(threshold_key))
        if threshold is None:
            continue
        above = rgb_to_hex(options.get(color_key), DEFAULT_COLOR)
        lines.append(
            f"{{%- if num is not none and num > {threshold!r} -%}}"
            f"{{%- set color = {jinja_str(above)} -%}}{{%- endif -%}}"
        )
    return lines


def _progress_lines(
    options: Mapping[str, Any], entity: str, keys: Mapping[str, str]
) -> list[str]:
    """Lines adding a progress bar to `page`, from a value between min and max."""
    source = options.get(CONF_PROGRESS_ENTITY) or entity
    source = _entity_id(source)
    low = _number(options.get(CONF_PROGRESS_MIN))
    high = _number(options.get(CONF_PROGRESS_MAX))
    low = DEFAULT_PROGRESS_MIN if low is None else low
    high = DEFAULT_PROGRESS_MAX if high is None else high
    if high <= low:
        raise InvalidSimpleOptionsError("the progress maximum must exceed the minimum")
    bar = (
        jinja_str(rgb_to_hex(options[CONF_PROGRESS_COLOR], DEFAULT_COLOR))
        if options.get(CONF_PROGRESS_COLOR)
        else "color"
    )
    background = jinja_str(
        rgb_to_hex(options.get(CONF_PROGRESS_BG), DEFAULT_PROGRESS_BG)
    )
    return [
        "{#- Progress bar: the value between min and max, as 0 to 100. -#}",
        f"{{%- set p = states({jinja_str(source)}) -%}}",
        "{%- if p | is_number -%}",
        f"{{%- set ratio = (p | float - {low!r}) / {high - low!r} -%}}",
        "{%- set page = dict(page, progress=([[ratio * 100, 0] | max, 100] | min)"
        f" | round(0) | int, {keys['progress_color']}={bar},"
        f" {keys['progress_bg']}={background}) -%}}",
        "{%- endif -%}",
    ]


def build_indicator_template(
    options: Mapping[str, Any], firmware: str = FIRMWARE_AWTRIX3
) -> str:
    """Template for a simple indicator: lit while an entity is in a state."""
    keys = _keys(firmware)
    entity = _entity_id(options.get(CONF_ENTITY_ID))
    active = str(options.get(CONF_ACTIVE_STATE) or DEFAULT_ACTIVE_STATE).strip()
    color = rgb_to_hex(options.get(CONF_COLOR), DEFAULT_INDICATOR_COLOR)
    effect = options.get(CONF_EFFECT, EFFECT_NONE)
    if effect not in EFFECTS:
        effect = EFFECT_NONE
    interval = int(options.get(CONF_EFFECT_INTERVAL) or DEFAULT_EFFECT_INTERVAL)
    interval = max(50, min(60000, interval))

    extra = f', "{keys[effect]}": {interval}' if effect != EFFECT_NONE else ""

    if indicator_color_mode(options) == COLOR_GRADIENT:
        return "\n".join(
            [
                HEADER,
                f"{{%- set raw = states({jinja_str(entity)}) -%}}",
                "{%- if raw | is_number -%}",
                "{%- set num = raw | float -%}",
                *_gradient_lines(options),
                f'{{{{ {{"color": color{extra}}} | tojson }}}}',
                "{%- else -%}",
                "{}",
                "{%- endif -%}",
            ]
        )

    payload = f'{{"color": {jinja_str(color)}{extra}}}'
    return "\n".join(
        [
            HEADER,
            f"{{%- if is_state({jinja_str(entity)}, {jinja_str(active)}) -%}}",
            f"{{{{ {payload} | tojson }}}}",
            "{%- else -%}",
            "{}",
            "{%- endif -%}",
        ]
    )
