export function translator(language) {
  const lang = (language || "en").split("-")[0];
  const table = STRINGS[lang] || STRINGS.en;
  return (key, params = {}) => {
    const path = key.split(".");
    let value = path.reduce((node, part) => (node ? node[part] : undefined), table);
    if (value === undefined) value = path.reduce((node, part) => (node ? node[part] : undefined), STRINGS.en);
    if (typeof value !== "string") return key;
    return value.replace(/\{(\w+)\}/g, (_m, name) => (name in params ? String(params[name]) : `{${name}}`));
  };
}
